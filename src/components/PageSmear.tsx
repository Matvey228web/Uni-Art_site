/**
 * Срыв всей картины разом.
 *
 * Два слоя размером с окно.
 *
 * Первый, page-smear, портит то, что под ним, через backdrop-filter.
 * Фильтровать само содержимое нельзя: замер на разделе 1280x900 дал
 * 376 мс сверх обычной отрисовки на полной цепочке и 107 мс на одном
 * смещении — фильтр на элементе Chromium считает процессором. Фон же
 * он фильтрует на видеокарте, и срыв обходится в те же 17 мс, что покой.
 *
 * Ссылку на SVG-фильтр внутри backdrop-filter понимает не всякий движок,
 * и подстелить запасное значение в том же свойстве нельзя: минификатор
 * схлопывает два объявления одного свойства в одно. Подмешать обычные
 * функции отдельными ступенями тоже не вышло — размытие фона оказалось
 * вчетверо дороже самого сноса строк.
 *
 * Второй, page-roll, вообще ничего не фильтрует: две заливки, у которых
 * меняется прозрачность, плюс светлая полоса, проезжающая сверху вниз.
 * Он работает везде и всегда, и не стоит ничего.
 *
 * Лежат выше шапки, чтобы срывалось всё сразу, но ниже модального окна.
 */
export default function PageSmear() {
  return (
    <>
      <div aria-hidden className="page-smear pointer-events-none fixed inset-0 z-[60]" />
      <div aria-hidden className="page-roll pointer-events-none fixed inset-0 z-[61]">
        <div className="page-wash page-wash-warm" />
        <div className="page-wash page-wash-dark" />
        <div className="page-bar" />
      </div>
    </>
  );
}
