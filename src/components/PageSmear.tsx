/**
 * Срыв всей картины разом.
 *
 * Слои размером с окно, которые портят то, что под ними. Фильтровать само
 * содержимое оказалось слишком дорого: на всю высоту документа браузер
 * отрисовывает страницу в текстуру, и кадр раздувается до 166 мс. Здесь
 * цена привязана к окну, а не к длине страницы.
 *
 * Слоя два, потому что они опираются на разные возможности движка.
 *
 * Первый, page-smear, тянет строки вбок ссылкой на SVG-фильтр. Это лучший
 * срыв из возможных, но ссылку на фильтр внутри backdrop-filter понимает
 * не всякий движок, и подстелить запасное значение в том же свойстве
 * нельзя: минификатор схлопывает два объявления одного свойства в одно.
 *
 * Поэтому второй, page-roll, собран только из функций, которые понимают
 * все: вспышка яркости, провал цвета и лёгкая расфокусировка — сбой
 * уровня сигнала. Плюс светлая полоса, проезжающая сверху вниз: так
 * выглядит сорванная кадровая синхронизация. Полоса вообще ничего не
 * фильтрует, она просто рисуется поверх, и работает везде.
 *
 * Где работают оба, они складываются: строки уезжают, и одновременно
 * по кадру идёт полоса. Где первый не работает — срыв всё равно виден.
 *
 * Лежат выше шапки, чтобы срывалось всё сразу, но ниже модального окна.
 */
export default function PageSmear() {
  return (
    <>
      <div aria-hidden className="page-smear pointer-events-none fixed inset-0 z-[60]" />
      <div aria-hidden className="page-roll pointer-events-none fixed inset-0 z-[61]">
        <div className="page-bar" />
      </div>
    </>
  );
}
